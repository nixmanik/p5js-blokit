import os

# Configuration
ASSETS_DIR = "game/assets/"
OUTPUT_FILE = "game/assets.js"
IMAGE_EXTS = {'.png', '.jpg', '.jpeg', '.gif'}
AUDIO_EXTS = {'.mp3', '.wav', '.ogg'}

def generate_manifest():
    images = {}
    audio = {}

    # Scan the directory
    for filename in os.listdir(ASSETS_DIR):
        name, ext = os.path.splitext(filename)
        ext = ext.lower()

        if ext in IMAGE_EXTS:
            images[name] = filename
        elif ext in AUDIO_EXTS:
            audio[name] = filename

    # Build the JS file content
    js_content = "/**\n * Auto-generated Asset Manifest\n * Do not edit this file manually.\n */\n"
    js_content += "const ASSET_MANIFEST = {\n"

    # Add images
    js_content += "    images: {\n"
    for key, val in images.items():
        js_content += f"        {key}: '{val}',\n"
    js_content += "    },\n"

    # Add audio
    js_content += "    audio: {\n"
    for key, val in audio.items():
        js_content += f"        {key}: '{val}',\n"
    js_content += "    }\n"

    js_content += "};"

    with open(OUTPUT_FILE, "w") as f:
        f.write(js_content)

    print(f"Successfully generated {OUTPUT_FILE} with {len(images)} images and {len(audio)} audio files.")

if __name__ == "__main__":
    generate_manifest()
